const RTL = ["ar"];
const DICT = { en: EN };
let lang = "en";
try {
  const v = localStorage.getItem(KEY);
  if (v && LANGS[v]) lang = v;
  else {
    const nav = (
      navigator.languages && navigator.languages.length
        ? navigator.languages
        : [navigator.language || "en"]
    ).map((x) => String(x).toLowerCase().split("-")[0]);
    lang = nav.find((x) => LANGS[x]) || "en";
    localStorage.setItem(KEY, lang);
  }
} catch {}

async function loadDict(l) {
  if (l === "tr" || DICT[l]) return DICT[l];
  try {
    const r = await fetch(`/l10n/${l}.json`, { cache: "force-cache" });
    DICT[l] = r.ok ? await r.json() : null;
  } catch {
    DICT[l] = null;
  }
  return DICT[l];
}
const word = (core) =>
  lang === "tr" ? core : (DICT[lang] && DICT[lang][core]) || EN[core] || core;

const SKIP = ["SCRIPT", "STYLE", "TEXTAREA"];
const orig = new WeakMap();
function tNode(n) {
  const raw = orig.has(n) ? orig.get(n) : n.nodeValue;
  const core = raw.trim();
  if (!core || !(core in EN)) return;
  if (!orig.has(n)) orig.set(n, raw);
  const lead = raw.slice(0, raw.length - raw.trimStart().length),
    trail = raw.slice(raw.trimEnd().length);
  n.nodeValue = lang === "tr" ? raw : lead + word(core) + trail;
}
function translate(root = document.body) {
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) =>
      n.parentElement && !SKIP.includes(n.parentElement.tagName)
        ? NodeFilter.FILTER_ACCEPT
        : NodeFilter.FILTER_REJECT,
  });
  const nodes = [];
  while (w.nextNode()) nodes.push(w.currentNode);
  nodes.forEach(tNode);
  root.querySelectorAll("[placeholder]").forEach((el) => {
    if (el instanceof HTMLElement) {
      if (!el.dataset.ph) el.dataset.ph = el.getAttribute("placeholder") || "";
      el.setAttribute(
        "placeholder",
        lang === "tr" ? el.dataset.ph : word(el.dataset.ph),
      );
    }
  });
}
const pickerLabel = () =>
  document.querySelectorAll("[data-lp-label]").forEach((el) => {
    el.textContent = LANGS[lang];
  });
async function setLang(l, save = true) {
  if (!LANGS[l]) l = "en";
  await loadDict(l);
  lang = l;
  if (save)
    try {
      localStorage.setItem(KEY, l);
    } catch {}
  const h = document.documentElement;
  h.lang = l;
  h.dir = RTL.includes(l) ? "rtl" : "ltr";
  const b = document.body.dataset;
  document.title =
    l === "tr"
      ? b.titleTr || ""
      : (DICT[l] && b.titleTr && DICT[l][b.titleTr]) || b.titleEn || "";
  document
    .querySelectorAll("[data-lang]")
    .forEach((x) => {
      if (x instanceof HTMLElement) {
        x.setAttribute("aria-pressed", String(x.dataset.lang === l));
      }
    });
  pickerLabel();
  translate();
}
const closeLp = () =>
  document.querySelectorAll("[data-lp][data-open]").forEach((p) => {
    p.removeAttribute("data-open");
    p.querySelector("[data-lp-btn]")?.setAttribute("aria-expanded", "false");
  });
document.addEventListener("click", (e) => {
  const target = e.target instanceof Element ? e.target : null;
  if (!target) return;
  const opt = target.closest("[data-lang]");
  if (opt instanceof HTMLElement) {
    setLang(opt.dataset.lang || "en");
    closeLp();
    return;
  }
  const btn = target.closest("[data-lp-btn]");
  const lp = btn?.closest("[data-lp]");
  if (lp) {
    const open = !lp.hasAttribute("data-open");
    closeLp();
    if (open) {
      lp.setAttribute("data-open", "");
      btn?.setAttribute("aria-expanded", "true");
      lp.querySelector('[aria-pressed="true"]')?.scrollIntoView({
        block: "nearest",
      });
    }
    return;
  }
  if (!target.closest("[data-lp]")) closeLp();
});
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") closeLp();
});

